fun dtcDesc(c: String): String {
    DTC[c]?.let { return it }
    val grp = when (c.take(1)) { "P" -> "موتور/گیربکس"; "C" -> "شاسی"; "B" -> "بدنه"; else -> "شبکه ارتباطی" }
    val sys = if (c.startsWith("P")) when (c.getOrNull(2)) {
        '1', '2' -> "، سیستم هوا/سوخت"; '3' -> "، سیستم جرقه/احتراق"; '4' -> "، کنترل آلایندگی"
        '5' -> "، سرعت/دور آرام"; '6' -> "، کامپیوتر خودرو"; '7', '8' -> "، گیربکس"; else -> ""
    } else ""
    val mf = if (c.getOrNull(1) == '1') " (کد اختصاصی سازنده؛ با تعمیرکار یا دفترچه بررسی شود)" else " (توضیح دقیق در لیست نیست؛ جست‌وجو کنید)"
    return grp + sys + mf
}
